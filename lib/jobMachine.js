export const JOB_STATUS = {
  DRAFT: 'DRAFT',
  REQUESTED: 'REQUESTED',
  COUNTERED: 'COUNTERED',
  CONFIRMED: 'CONFIRMED',
  STARTED: 'STARTED',
  EXTRA_PENDING: 'EXTRA_PENDING',
  COMPLETED: 'COMPLETED',
  RATED: 'RATED',
  DECLINED: 'DECLINED',
  CANCELLED: 'CANCELLED',
};

export const TRANSITIONS = {
  [JOB_STATUS.DRAFT]: [JOB_STATUS.REQUESTED],
  [JOB_STATUS.REQUESTED]: [
    JOB_STATUS.COUNTERED,
    JOB_STATUS.CONFIRMED,
    JOB_STATUS.DECLINED,
    JOB_STATUS.CANCELLED,
  ],
  [JOB_STATUS.COUNTERED]: [
    JOB_STATUS.CONFIRMED,
    JOB_STATUS.DECLINED,
    JOB_STATUS.CANCELLED,
  ],
  [JOB_STATUS.CONFIRMED]: [JOB_STATUS.STARTED, JOB_STATUS.CANCELLED],
  [JOB_STATUS.STARTED]: [
    JOB_STATUS.EXTRA_PENDING,
    JOB_STATUS.COMPLETED,
    JOB_STATUS.CANCELLED,
  ],
  [JOB_STATUS.EXTRA_PENDING]: [JOB_STATUS.STARTED],
  [JOB_STATUS.COMPLETED]: [JOB_STATUS.RATED],
  [JOB_STATUS.RATED]: [],
  [JOB_STATUS.DECLINED]: [],
  [JOB_STATUS.CANCELLED]: [],
};

/**
 * Validates whether state transition is allowed
 */
export function canTransition(currentStatus, nextStatus) {
  if (!currentStatus || !nextStatus) return false;
  const allowed = TRANSITIONS[currentStatus] || [];
  return allowed.includes(nextStatus);
}
